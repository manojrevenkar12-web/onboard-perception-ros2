#!/usr/bin/env python3
"""Measures what moving a camera frame between nodes costs, four ways, with and without a CPU limit.

  raw        separate processes, sensor_msgs/Image through the middleware (Fast DDS, default config)
  raw_reliable    the same with reliable QoS (lost fragments are resent)
  raw_large_data  the same with FASTDDS_BUILTIN_TRANSPORTS=LARGE_DATA (Fast DDS's large-sample setup)
  shm        separate processes, opr shm transport via image_transport (one copy out at the reader)
  zero_copy  separate processes, reader works on the leased shared-memory slot in place
  intra      one process, intra-process communication (the composed-container baseline)

"one core" pins both processes to CPU 0 with taskset, the way a busy companion computer leaves
perception one core. Writes reports/benchmarks/transport.json and .md.
Usage: run_transport.py <repo>/reports/benchmarks [--frames 300]
"""
import argparse
import json
import os
import subprocess
import sys
import tempfile
import time

SIZES = [("1920x1080 YUYV", 1920, 1080, 2), ("640x480 mono8", 640, 480, 1)]
MODES = ["raw", "raw_reliable", "raw_large_data", "shm", "zero_copy", "intra"]
LIMITS = [("none", []), ("one core", ["taskset", "-c", "0"])]


def exe(name):
    from ament_index_python.packages import get_package_prefix

    return os.path.join(get_package_prefix("opr_bench"), "lib", "opr_bench", name)


def run(mode, width, height, bpp, frames, prefix):
    tmp = tempfile.mkdtemp(prefix="opr_bench_")
    base = os.path.join(tmp, "r")
    env = dict(os.environ, RCUTILS_LOGGING_SEVERITY_THRESHOLD="WARN")
    if mode == "raw_large_data":
        # Fast DDS's own answer to large samples between local processes (shared memory + TCP).
        env["FASTDDS_BUILTIN_TRANSPORTS"] = "LARGE_DATA"
    sub_mode = "raw" if mode in ("raw_large_data", "raw_reliable") else mode
    reliable = "true" if mode == "raw_reliable" else "false"
    if mode == "intra":
        subprocess.run(prefix + [exe("bench_intra"), base, str(width), str(height), str(bpp), str(frames)],
                       env=env, check=True, timeout=frames / 30 + 60)
    else:
        sub = subprocess.Popen(prefix + [exe("bench_sub"), "--ros-args",
                                         "-p", f"mode:={sub_mode}", "-p", f"reliable:={reliable}",
                                         "-p", f"output:={base}.sub.json"], env=env)
        time.sleep(1.0)
        subprocess.run(prefix + [exe("bench_pub"), "--ros-args",
                                 "-p", f"width:={width}", "-p", f"height:={height}", "-p", f"bytes_per_pixel:={bpp}",
                                 "-p", f"frames:={frames}", "-p", f"reliable:={reliable}", "-p", f"output:={base}.pub.json"],
                       env=env, check=True, timeout=frames / 30 + 60)
        time.sleep(0.5)
        sub.send_signal(2)
        sub.wait(timeout=20)
    with open(base + ".pub.json") as f:
        pub = json.load(f)
    with open(base + ".sub.json") as f:
        res = json.load(f)
    res.update(pub)
    total = res["publisher_cpu_s"] + res["subscriber_cpu_s"]
    res["cpu_ms_per_frame"] = 1000.0 * total / max(res["received"], 1)  # per delivered frame
    res["cpu_ms_per_sent_frame"] = 1000.0 * total / max(res["sent"], 1)
    return res


NAMES = {
    "raw": "raw, default QoS (best effort)",
    "raw_reliable": "raw, reliable QoS",
    "raw_large_data": "raw, Fast DDS LARGE_DATA",
    "shm": "shm, one copy at the reader",
    "zero_copy": "shm, read in place",
    "intra": "intra-process, one process",
}


def write_markdown(out_dir, info, results):
    lines = [
        "# Moving a frame between nodes",
        "",
        f"Machine: {info['cpus']} vCPU, {info['cpu_model']}; middleware {info['rmw']}; "
        f"{info['frames_per_run']} frames at {info['rate_hz']} Hz per run; every path except the last is two processes. "
        "Generated by `opr_bench/scripts/run_transport.py`. Latency is publish call to the subscriber's callback "
        "(after any copy). CPU is publisher plus subscriber process time; per delivered frame it charges lost "
        "frames' cost to the ones that arrived, per sent frame it does not.",
        "",
        "| Frame | CPU limit | Path | Delivered | Latency p50 | p99 | CPU per delivered frame | per sent frame |",
        "|---|---|---|---:|---:|---:|---:|---:|",
    ]
    for r in results:
        lines.append(f"| {r['size']} | {r['limit']} | {NAMES[r['mode']]} | {r['received']}/{r['sent']} | "
                     f"{r['latency_ms_p50']:.2f} ms | {r['latency_ms_p99']:.2f} ms | {r['cpu_ms_per_frame']:.2f} ms | "
                     f"{r.get('cpu_ms_per_sent_frame', 1000.0 * (r['publisher_cpu_s'] + r['subscriber_cpu_s']) / r['sent']):.2f} ms |")
    with open(os.path.join(out_dir, "transport.md"), "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir")
    ap.add_argument("--frames", type=int, default=300)
    ap.add_argument("--markdown-only", action="store_true", help="rewrite transport.md from transport.json")
    args = ap.parse_args()
    os.makedirs(args.out_dir, exist_ok=True)
    if args.markdown_only:
        with open(os.path.join(args.out_dir, "transport.json")) as f:
            data = json.load(f)
        write_markdown(args.out_dir, data["machine"], data["results"])
        return 0
    results = []
    for size_name, w, h, bpp in SIZES:
        for limit_name, prefix in LIMITS:
            for mode in MODES:
                r = run(mode, w, h, bpp, args.frames, prefix)
                r.update({"size": size_name, "limit": limit_name, "mode": mode})
                results.append(r)
                print(f"{size_name:16} {limit_name:9} {mode:10} received {r['received']}/{r['sent']} "
                      f"p50 {r['latency_ms_p50']:.2f} ms p99 {r['latency_ms_p99']:.2f} ms "
                      f"cpu {r['cpu_ms_per_frame']:.2f} ms/frame", flush=True)
    info = {
        "cpus": os.cpu_count(),
        "cpu_model": next((l.split(":", 1)[1].strip() for l in open("/proc/cpuinfo") if l.startswith("model name")), "?"),
        "frames_per_run": args.frames,
        "rate_hz": 30,
        "rmw": os.environ.get("RMW_IMPLEMENTATION", "rmw_fastrtps_cpp (default)"),
    }
    with open(os.path.join(args.out_dir, "transport.json"), "w") as f:
        json.dump({"machine": info, "results": results}, f, indent=2)
    write_markdown(args.out_dir, info, results)
    return 0


if __name__ == "__main__":
    sys.exit(main())
